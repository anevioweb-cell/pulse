import { z } from 'zod/mini';

import { API, PROTOCOL, SENSOR_RANGES } from '../config';
import { deviceIdSchema, deviceSchema } from '../model/device';
import { sensorReadingSchema } from '../model/reading';
import { untrustedIdentifier, untrustedText } from '../model/untrusted';

// REST contract v1. The mock server validates requests with these schemas and HttpTelemetryApi
// validates responses with them; DemoTelemetryApi produces values that satisfy them. Every object
// is strict (no extra keys) and every array is length-capped.

const MAX_DEVICES_PER_RESPONSE = 256;

/**
 * Where data comes from, so the UI can label it honestly:
 * - `simulated`: generated by the SimulationEngine / HistoryModel (Demo Mode, mock server fleet).
 * - `device`: reported by real hardware.
 */
export const dataSourceSchema = z.enum(['simulated', 'device']);
export type DataSource = z.infer<typeof dataSourceSchema>;

export const metricSchema = z.enum(['temperature', 'humidity', 'pressure', 'battery', 'signal']);
export type Metric = z.infer<typeof metricSchema>;

const timestampSchema = z
  .int()
  .check(z.gte(PROTOCOL.MIN_TIMESTAMP_MS), z.lte(PROTOCOL.MAX_TIMESTAMP_MS));

const rangeOf = (metric: Metric) => new Map(Object.entries(SENSOR_RANGES)).get(metric);

/* ------------------------------------------- devices ------------------------------------------ */

export const deviceSummarySchema = z.extend(deviceSchema, { source: dataSourceSchema });
export type DeviceSummary = z.infer<typeof deviceSummarySchema>;

export const deviceListResponseSchema = z.strictObject({
  devices: z.array(deviceSummarySchema).check(z.maxLength(MAX_DEVICES_PER_RESPONSE)),
});

export const latestReadingSchema = z.strictObject({
  ts: timestampSchema,
  values: sensorReadingSchema,
});

export const deviceDetailSchema = z.extend(deviceSummarySchema, {
  /** Most recent reading known to the server, or null if it has none. */
  latest: z.nullable(latestReadingSchema),
});
export type DeviceDetail = z.infer<typeof deviceDetailSchema>;

/* ------------------------------------------- readings ----------------------------------------- */

/** Query string of GET /api/devices/:id/readings (strings in, numbers out). */
export const readingsQuerySchema = z
  .strictObject({
    from: z.coerce
      .number()
      .check(z.int(), z.gte(PROTOCOL.MIN_TIMESTAMP_MS), z.lte(PROTOCOL.MAX_TIMESTAMP_MS)),
    to: z.coerce
      .number()
      .check(z.int(), z.gte(PROTOCOL.MIN_TIMESTAMP_MS), z.lte(PROTOCOL.MAX_TIMESTAMP_MS)),
    metric: metricSchema,
    maxPoints: z.optional(
      z.coerce.number().check(z.int(), z.gte(API.MIN_POINTS), z.lte(API.MAX_POINTS)),
    ),
  })
  .check(
    z.refine((query) => query.to > query.from, { message: 'to must be after from', path: ['to'] }),
    z.refine((query) => query.to - query.from <= API.MAX_RANGE_MS, {
      message: 'range too long',
      path: ['to'],
    }),
  );
/** What callers pass (the schema also accepts the query-string form). */
export interface ReadingsQueryInput {
  from: number;
  to: number;
  metric: Metric;
  maxPoints?: number;
}
export type ReadingsQuery = z.output<typeof readingsQuerySchema>;

export const resolutionSchema = z.strictObject({
  /** `raw`: every stored sample. `min-max`: each bucket's minimum and maximum (downsampled). */
  method: z.enum(['raw', 'min-max']),
  /** Spacing of the stored samples the series was computed from. */
  sampleIntervalMs: z.int().check(z.gt(0)),
  /** Raw samples per bucket (1 for raw). */
  bucketSize: z.int().check(z.gte(1)),
  rawCount: z.int().check(z.gte(0)),
  returnedCount: z.int().check(z.gte(0), z.lte(API.MAX_POINTS)),
});

export const historicalReadingsSchema = z
  .strictObject({
    deviceId: deviceIdSchema,
    metric: metricSchema,
    from: timestampSchema,
    to: timestampSchema,
    source: dataSourceSchema,
    resolution: resolutionSchema,
    timestamps: z.array(timestampSchema).check(z.maxLength(API.MAX_POINTS)),
    values: z.array(z.number()).check(z.maxLength(API.MAX_POINTS)),
  })
  .check(
    z.refine((r) => r.timestamps.length === r.values.length, {
      message: 'length mismatch',
      path: ['values'],
    }),
    z.refine((r) => r.resolution.returnedCount === r.timestamps.length, {
      message: 'returnedCount mismatch',
      path: ['resolution', 'returnedCount'],
    }),
    z.refine((r) => r.timestamps.every((t, i) => i === 0 || t >= (r.timestamps.at(i - 1) ?? t)), {
      message: 'timestamps not sorted',
      path: ['timestamps'],
    }),
    z.refine(
      (r) => {
        const range = rangeOf(r.metric);
        return !!range && r.values.every((v) => v >= range.min && v <= range.max);
      },
      { message: 'value out of range', path: ['values'] },
    ),
  );
export type HistoricalReadings = z.infer<typeof historicalReadingsSchema>;

/* -------------------------------------------- alerts ------------------------------------------ */

export const comparatorSchema = z.enum(['above', 'below']);
export const ruleIdSchema = untrustedIdentifier(PROTOCOL.DEVICE_ID_MAX_LENGTH);

/** Body of POST /api/alert-rules and PUT /api/alert-rules/:id (full replacement). */
export const alertRuleInputSchema = z
  .strictObject({
    name: untrustedText(API.RULE_NAME_MAX_LENGTH),
    /** null: applies to every device. */
    deviceId: z.nullable(deviceIdSchema),
    metric: metricSchema,
    comparator: comparatorSchema,
    threshold: z.number(),
    enabled: z.boolean(),
  })
  .check(
    z.refine(
      (rule) => {
        const range = rangeOf(rule.metric);
        return !!range && rule.threshold >= range.min && rule.threshold <= range.max;
      },
      { message: 'threshold outside the metric range', path: ['threshold'] },
    ),
  );
export type AlertRuleInput = z.infer<typeof alertRuleInputSchema>;

export const alertRuleSchema = z.extend(alertRuleInputSchema, { id: ruleIdSchema });
export type AlertRule = z.infer<typeof alertRuleSchema>;

export const alertRuleListResponseSchema = z.strictObject({
  rules: z.array(alertRuleSchema).check(z.maxLength(API.MAX_ALERT_RULES)),
});

/** Query string of GET /api/alerts. */
export const alertsQuerySchema = z
  .strictObject({
    from: z.coerce
      .number()
      .check(z.int(), z.gte(PROTOCOL.MIN_TIMESTAMP_MS), z.lte(PROTOCOL.MAX_TIMESTAMP_MS)),
    to: z.coerce
      .number()
      .check(z.int(), z.gte(PROTOCOL.MIN_TIMESTAMP_MS), z.lte(PROTOCOL.MAX_TIMESTAMP_MS)),
    limit: z.optional(z.coerce.number().check(z.int(), z.gte(1), z.lte(API.MAX_ALERT_LIMIT))),
  })
  .check(
    z.refine((query) => query.to > query.from, { message: 'to must be after from', path: ['to'] }),
    z.refine((query) => query.to - query.from <= API.MAX_ALERT_RANGE_MS, {
      message: 'range too long',
      path: ['to'],
    }),
  );
export interface AlertsQueryInput {
  from: number;
  to: number;
  limit?: number;
}
export type AlertsQuery = z.output<typeof alertsQuerySchema>;

export const alertEventSchema = z.strictObject({
  id: untrustedIdentifier(API.ALERT_ID_MAX_LENGTH),
  ruleId: ruleIdSchema,
  ruleName: untrustedText(API.RULE_NAME_MAX_LENGTH),
  deviceId: deviceIdSchema,
  metric: metricSchema,
  comparator: comparatorSchema,
  threshold: z.number(),
  value: z.number(),
  /** When the value crossed the threshold. */
  ts: timestampSchema,
  source: dataSourceSchema,
});
export type AlertEvent = z.infer<typeof alertEventSchema>;

export const alertHistorySchema = z.strictObject({
  /** Newest first. */
  alerts: z.array(alertEventSchema).check(z.maxLength(API.MAX_ALERT_LIMIT)),
  /** More events matched than `limit` allowed. */
  truncated: z.boolean(),
});
export type AlertHistory = z.infer<typeof alertHistorySchema>;

/* -------------------------------------------- errors ------------------------------------------ */

export const errorCodeSchema = z.enum([
  'bad_request',
  'not_found',
  'method_not_allowed',
  'forbidden_origin',
  'payload_too_large',
  'uri_too_long',
  'unsupported_media_type',
  'limit_reached',
  'rate_limited',
  'injected_fault',
  'internal',
]);
export type ErrorCode = z.infer<typeof errorCodeSchema>;
